"""CLI: python -m utility_data "ADDRESS" --utility pge|sce|nationalgrid_ma [--site-id ID] [--out DIR]

The utility comes from the customer's bill and is never guessed. Writes:
  <out>/<utility>__<address-slug>.json   the site record
  <out>/index.json                       list of records (for the mockup)
  assets/utility_records.js              same records as window.UTILITY_RECORDS (static page, no fetch needed)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from .adapters import ADAPTERS, KNOWN_WITHOUT_ADAPTER
from .geo import geocode
from .http import Http
from .record import finalize_gaps, new_record, val

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "data" / "site_records"
BUNDLE = ROOT / "assets" / "utility_records.js"


def build(address: str, utility: str, http: Http | None = None) -> dict:
    http = http or Http()
    rec = new_record(address, utility)
    if utility in ADAPTERS:
        name, fill = ADAPTERS[utility]
    else:
        name, map_url = KNOWN_WITHOUT_ADAPTER.get(utility, (utility, None))
        rec["utility"] = val(name, "Customer bill (input)", "input:--utility", "high")
        rec["notes"].append(f"No adapter yet for '{utility}'. Hosting capacity map: {map_url or 'not known yet'}. Every field is a gap.")
        lonlat = geocode(http, address, rec)
        return finalize_gaps(rec, {"*": f"No adapter for {name} yet."})
    rec["utility"] = val(name, "Customer bill (input)", "input:--utility", "high", note="Utility is an input from the bill; never inferred.")
    lonlat = geocode(http, address, rec)
    if not lonlat:
        return finalize_gaps(rec, {"*": "Geocoding failed, so the utility map could not be queried."})
    try:
        reasons = fill(http, rec, *lonlat)
    except Exception as e:  # never crash; record it
        rec["errors"].append(f"{name} adapter failed: {type(e).__name__}: {e}")
        reasons = {"*": "Adapter error (see errors)."}
    return finalize_gaps(rec, reasons)


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:80]


def write(rec: dict, out: Path, site_id: str | None) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    if site_id:
        rec["site_id"] = site_id
    path = out / f"{rec['input']['utility']}__{slug(rec['input']['address'])}.json"
    path.write_text(json.dumps(rec, indent=2))
    records = [json.loads(p.read_text()) for p in sorted(out.glob("*__*.json"))]
    (out / "index.json").write_text(json.dumps([{"file": f"{r['input']['utility']}__{slug(r['input']['address'])}.json", "site_id": r.get("site_id"),
                                                 "address": r["input"]["address"], "utility": r["input"]["utility"], "generated_at": r["generated_at"]}
                                                for r in records], indent=2))
    if out.resolve() != DEFAULT_OUT.resolve():
        return path  # only the default folder feeds the mockup bundle
    BUNDLE.write_text("/* Generated by `python -m utility_data`; do not edit. Utility hosting-capacity site records. */\n"
                      f"window.UTILITY_RECORDS = {json.dumps(records)};\n")
    return path


def summary(rec: dict) -> str:
    def v(x):
        return "—" if x is None else f"{x['value']}{(' ' + x['unit']) if x.get('unit') else ''} [{x['confidence']}]" + (f" (data {x['data_date']})" if x.get("data_date") else "")
    h, f = rec["hosting_capacity"], rec["feeder"]
    lines = [f"{rec['input']['address']}  ·  {rec['utility']['value'] if rec['utility'] else rec['input']['utility']}",
             f"  site:        {v(rec['site']['lat'])}, {v(rec['site']['lon'])}",
             f"  feeder:      {v(f['name'])}  id {v(f['id'])}",
             f"  substation:  {v(f['substation'])}   division: {v(f['division'])}",
             f"  voltage:     {v(rec['feeder_voltage_kv'])}   phases: {v(rec['phases'])}",
             f"  generation:  {v(h['generation'])}",
             f"  load:        {v(h['load'])}",
             f"  computed:    {v(h['computed'])}",
             f"  limiting:    {v(h['limiting_criteria'])}"]
    if rec.get("match"):
        lines.append(f"  match:       {rec['match']['method']}")
    lines.append(f"  gaps:        {', '.join(g['field'] for g in rec['gaps']) or 'none'}  (+{len(rec['site_gaps'])} site items for the customer/utility)")
    for n in rec["notes"]:
        lines.append(f"  note:        {n}")
    for e in rec["errors"]:
        lines.append(f"  ERROR:       {e}")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="site_record", description="Build a utility site record from public hosting-capacity data.")
    ap.add_argument("address")
    ap.add_argument("--utility", required=True, help=f"From the customer's bill. Adapters: {', '.join(ADAPTERS)}; anything else records 'no adapter yet'.")
    ap.add_argument("--site-id", help="Mockup facility id to attach this record to (e.g. tennessee-888)")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args(argv)
    rec = build(a.address, a.utility.lower())
    path = write(rec, Path(a.out), a.site_id)
    print(summary(rec))
    print(f"  written:     {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
